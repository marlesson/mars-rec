"""Dependency-upgrade regression guards.

The rest of the suite checks *behaviour* (artifacts exist, shapes, metric
formulas). These tests check *numbers* and *backward compatibility*: the two
things that can change silently when ``requirements.lock`` is upgraded
(new torch kernels, pandas/numpy semantics, pickle or checkpoint formats).

- ``TestLegacyArtifacts`` loads a ``weights.ckpt`` + ``index_mapping.pkl`` +
  ``params.json`` trio produced by an older stack (versions recorded in
  ``expected_scores.json``) and checks the scores are reproduced. A failure
  means models already trained in production (e.g. on a Vertex AI image)
  would stop loading or would score differently after the upgrade.
- ``TestGoldenTrainingHistory`` re-runs a seeded training on the fixture
  project and compares ``history.csv`` with ``golden_history.json``.

Fixtures are generated by ``scripts/make_regression_fixtures.py``. Do not
regenerate ``legacy_artifacts`` to make a failure go away: that defeats its
purpose. Refresh ``golden_history.json`` only after reviewing the drift.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from tests._fixtures.regression import SCORING_INPUT, build_training_task, score_fixed_input

FIXTURES_DIR = Path(__file__).parent / "_fixtures"
LEGACY_DIR = FIXTURES_DIR / "legacy_artifacts"
GOLDEN_HISTORY_PATH = FIXTURES_DIR / "golden_history.json"

# Inference on a fixed checkpoint is deterministic on CPU; allow only
# float32 round-off across library versions.
SCORE_ATOL = 1e-5
# Training goes through stochastic kernels whose implementation can change
# between torch releases. 3 epochs on 60 rows keeps the expected drift well
# below this; anything larger deserves a look before refreshing the golden.
HISTORY_ATOL = 1e-2


def _staged_legacy_dir(tmp_path: Path) -> Path:
    """Copy the fixture so tests never write next to the committed files."""
    dst = tmp_path / "legacy"
    shutil.copytree(LEGACY_DIR, dst)
    return dst


class TestLegacyArtifacts:
    def test_legacy_checkpoint_reproduces_scores(self, tmp_path):
        with open(LEGACY_DIR / "expected_scores.json") as f:
            expected = json.load(f)
        assert expected["input"] == SCORING_INPUT, "fixture input drifted from tests/_fixtures/regression.py"

        scores = score_fixed_input(str(_staged_legacy_dir(tmp_path)))

        np.testing.assert_allclose(
            scores,
            expected["scores"],
            atol=SCORE_ATOL,
            err_msg=f"legacy checkpoint scores changed (generated with {expected['generated_with']})",
        )

    def test_run_inference_on_legacy_artifacts(self, tmp_path):
        """``mars-rec predict`` path end to end on artifacts from the old stack:
        parquet read (pyarrow), preprocessing, top-k and reverse mapping."""
        from mars_rec.inference import run_inference

        task_dir = _staged_legacy_dir(tmp_path)
        data_path = tmp_path / "inputs.parquet"
        pd.DataFrame({k: v for k, v in SCORING_INPUT.items() if k != "label"}).to_parquet(data_path)

        result = run_inference(
            task_dir=str(task_dir),
            data_path=str(data_path),
            output_path=str(tmp_path / "result.json"),
            batch_size=4,
            k=3,
            device="cpu",
        )

        assert result["user"] == SCORING_INPUT["user_id"]
        assert len(result["top10s"]) == len(SCORING_INPUT["user_id"])
        assert json.loads((tmp_path / "result.json").read_text())["user"] == result["user"]

    def test_legacy_index_mapping_keeps_reserved_slots(self):
        import math
        import pickle

        with open(LEGACY_DIR / "index_mapping.pkl", "rb") as f:
            idx = pickle.load(f)

        assert idx["item_id"].get("-1") == 2
        assert idx["item_id"].get(None) == 1
        assert [v for k, v in idx["item_id"].items() if isinstance(k, float) and math.isnan(k)] == [1]
        # defaultdict(int) must survive unpickling: unseen ids fall back to OOV=0.
        assert idx["item_id"]["never-seen-item"] == 0


@pytest.mark.slow
class TestGoldenTrainingHistory:
    @pytest.fixture
    def lifecycle_env(self, tmp_path, monkeypatch):
        import luigi

        luigi.task_register.Register.clear_instance_cache()
        monkeypatch.setenv("MARS_TEST_DATASET_DIR", str(tmp_path / "ds"))
        monkeypatch.chdir(tmp_path)
        return tmp_path

    def test_seeded_training_matches_golden_history(self, lifecycle_env):
        with open(GOLDEN_HISTORY_PATH) as f:
            golden = json.load(f)

        task = build_training_task()
        task.requires().run()
        task.run()
        history = pd.read_csv(Path(task.output().path) / "history.csv")

        expected = golden["history"]
        assert list(history.columns) == list(expected.keys())
        assert history["epoch"].tolist() == expected["epoch"]
        for col in expected:
            if col == "epoch":
                continue
            np.testing.assert_allclose(
                history[col].to_numpy(),
                expected[col],
                atol=HISTORY_ATOL,
                err_msg=f"{col} drifted from golden (generated with {golden['generated_with']})",
            )
